import { useEffect } from "react";

/* ============================================================
   טוען סקריפט ואנילה מ-public/js ומריץ אותו מחדש בכל עלייה של
   הקומפוננטה.
   ------------------------------------------------------------
   למה לא לשכתב את הסקריפטים האלה ל-React: הם מכילים את הגלריה
   התלת-ממדית (WebGL/OGL), אנימציית הלוגו ואפקט חשיפת הווידאו -
   קוד שנבנה ואומת פיקסל-אחר-פיקסל מול האתר החי. שכתוב שלהם היה
   מסכן את הנאמנות בלי להוסיף ערך. הם כתובים כ-IIFE שמחפש אלמנט
   מארח ויוצא בשקט אם הוא לא קיים, ולכן בטוח להריץ אותם שוב.

   פרמטר ה-v מכריח טעינה מחדש: בלעדיו הדפדפן מגיש את הסקריפט
   מהקאש בלי להריץ את ה-IIFE שוב, והרכיב היה נשאר ריק אחרי
   חזרה לעמוד.
   ============================================================ */
export function useLegacyScript(src: string, enabled = true) {
  useEffect(() => {
    if (!enabled) return;

    const el = document.createElement("script");
    el.src = `${src}?v=${Date.now()}`;
    el.async = false;
    document.body.appendChild(el);

    return () => {
      el.remove();
    };
  }, [src, enabled]);
}
